// 옷 다음에 오는 것은 입이다. 입의 시작을 옷 조각의 끝으로 삼는다.
const MOUTH_STARTS = ['<mask id="mouth', 'M363 533c6.08', "M443 515.1c-5.6"];

function patternDefs(uid, p) {
  const size = Math.max(8, Math.min(120, Number(p.size) || 40));
  const color = "#" + String(p.color || "ffffff").replace(/^#/, "");
  const angle = Number(p.angle) || 0;
  const id = `pat_${uid}`;
  let body;
  if (p.kind === "dot") {
    body = `<circle cx="${size / 2}" cy="${size / 2}" r="${size * 0.16}" fill="${color}"/>`;
  } else if (p.kind === "check") {
    body =
      `<rect width="${size}" height="${size * 0.28}" fill="${color}" fill-opacity="0.85"/>` +
      `<rect width="${size * 0.28}" height="${size}" fill="${color}" fill-opacity="0.85"/>`;
  } else {
    // stripe — angle 로 가로/세로/사선을 만든다
    body = `<rect width="${size}" height="${size * 0.42}" fill="${color}"/>`;
  }
  return {
    id,
    def:
      `<pattern id="${id}" width="${size}" height="${size}" patternUnits="userSpaceOnUse"` +
      (angle ? ` patternTransform="rotate(${angle})"` : "") +
      `>${body}</pattern>`,
  };
}

/** 옷 위에 무늬를 덧그린다. pattern.kind 가 없거나 'none' 이면 아무것도 안 한다. */
export function overlayClothesPattern(svg, pattern, clothesId, uid = "a") {
  if (!pattern || !pattern.kind || pattern.kind === "none") return svg;
  const anchor = CLOTHES_ANCHORS[clothesId];
  if (!anchor) return svg;

  const at = svg.indexOf(anchor);
  if (at < 0) return warnMissing("옷 무늬"), svg;
  const start = svg.lastIndexOf("<path", at);
  let end = -1;
  for (const m of MOUTH_STARTS) {
    const i = svg.indexOf(m, at);
    if (i >= 0 && (end < 0 || i < end)) end = i;
  }
  if (end >= 0) end = svg.lastIndexOf("<", end); // 입 요소의 여는 괄호 앞까지
  if (start < 0 || end <= start) return warnMissing("옷 무늬"), svg;

  const chunk = svg.slice(start, end);
  const clip = `clothes_${uid}`;
  const { id, def } = patternDefs(uid, pattern);
  // 옷 조각을 그대로 clipPath 로 재사용한다(clipPath 는 칠 속성을 무시하고 모양만 쓴다).
  const overlay =
    `<defs><clipPath id="${clip}">${chunk}</clipPath>${def}</defs>` +
    `<g clip-path="url(#${clip})"><rect x="0" y="0" width="768" height="768" fill="url(#${id})"/></g>`;

  return svg.slice(0, end) + overlay + svg.slice(end);
}

// ── 빌트인 옷의 장식 제거 ─────────────────────────────────────────────────
// 셔츠 가슴에 지그재그 장식(검정 20%)이 박혀 있는데, 무늬처럼 보여서 어색하다.
// 우리가 옷 무늬를 따로 그리게 되면서 더 지저분해져 걷어낸다.
const SHIRT_ZIGZAG =
  '<path d="M336.5 715 302 652l34.5 52.5L379 670zm94 0 34.5-63-34.5 52.5L389 670z" fill="black" fill-opacity="0.2"/>';

export function cleanClothes(svg) {
  return svg.replace(SHIRT_ZIGZAG, "");
}

// ── 안경 ──────────────────────────────────────────────────────────────────
// toonHead 에는 안경 컴포넌트가 아예 없다(beard/body/clothes/eyebrows/eyes/hair/head/mouth/rearHair 가 전부).
// 그래서 안경은 새로 그려서 맨 위에 덧씌운다. 눈 위에 얹히므로 z-order 문제도 없다.
const FRAME = "#2B2B2B";

// 원본 눈동자 중심. 안경을 여기에 맞춰야 얼굴과 어긋나지 않는다.
const EYE_L = 314;
const EYE_R = 453;
const EYE_Y = 412;

function glassesSvg(shape) {
  const lens =
    shape === "round"
      ? `<circle cx="${EYE_L}" cy="${EYE_Y}" r="52"/><circle cx="${EYE_R}" cy="${EYE_Y}" r="52"/>`
      : `<rect x="${EYE_L - 54}" y="${EYE_Y - 40}" width="108" height="80" rx="14"/>` +
        `<rect x="${EYE_R - 54}" y="${EYE_Y - 40}" width="108" height="80" rx="14"/>`;
  return `<g fill="none" stroke="${FRAME}" stroke-width="9" stroke-linecap="round">
    ${lens}
    <path d="M${EYE_L + 54} ${EYE_Y - 6}h${EYE_R - EYE_L - 108}"/>
    <path d="M${EYE_L - 54} ${EYE_Y - 10}l-46-12"/>
    <path d="M${EYE_R + 54} ${EYE_Y - 10}l46-12"/>
  </g>`;
}

export const GLASSES_OPTIONS = [
  { id: "none", label: "없음" },
  { id: "round", label: "동그란 안경" },
  { id: "square", label: "각진 안경" },
];

/** 완성된 SVG 맨 위에 안경을 덧씌운다. */
export function overlayGlasses(svg, glassesId) {
  if (!glassesId || glassesId === "none") return svg;
  return insertIntoBody(svg, glassesSvg(glassesId));
}

/**
 * DiceBear 가 만든 SVG 문자열 뒤에 커스텀 파츠를 덧그린다.
 * toonHead 의 z-order 는 ... eyes → eyebrows → hair 순서라, 맨 끝에 붙이면 hair 자리와 같다.
 */
export function overlayCustomHair(svg, hairId, colors) {
  const part = CUSTOM_HAIR[hairId];
  if (!part) return svg;
  return insertIntoBody(svg, part.svg(colors));
}
