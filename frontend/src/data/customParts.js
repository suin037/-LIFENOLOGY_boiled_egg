// 앵커는 눈썹 path 의 시작 좌표(M305.33) — 이건 색과 무관하게 고정이다.
const NEUTRAL_BROWS_RE = /<g fill="[^"]*"><path d="M305\.33[\s\S]*?<\/g>/;

const MIRROR = 767; // 얼굴 좌우 대칭축 x=383.5 기준. 오른쪽 x = MIRROR - 왼쪽 x

/** 왼쪽 눈썹 곡선(절대좌표). 오른쪽은 자동으로 좌우 반전한다. */
