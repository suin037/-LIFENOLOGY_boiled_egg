// ── 속눈썹 ───────────────────────────────────────────────────────────────
// 빌트인 눈(크게 뜬·웃는)은 윗눈꺼풀 path 끝에 바깥쪽으로 삐져나온 꼬리가 붙어 있다.
// 그게 속눈썹이다. path 를 통째로 지우면 눈꺼풀 선까지 사라져 눈이 허옇게 뜨므로
// 꼬리 좌표만 잘라내고 그 자리에서 닫는다(z). 눈꺼풀은 남고 속눈썹만 없어진다.
//
// 처음엔 뾰족한 끝만 잘라내 봤는데, 어떻게 잘라도 단면이 남아 '자른 티'가 났다.
// Figma 원본을 열어보니 속눈썹은 eye-lash 라는 독립 벡터고, 이걸 통째로 빼면
// 작가가 그린 흰자(둥근 아몬드)와 눈동자만 남는다 — 잘린 데 없이 둥근 눈이 된다.
//
// 좌/우 각각 시작 좌표와 채움색으로 특정한다('wide' 는 M, 'happy' 는 m 으로 시작).
const LASH_PATHS = [
  /<path d="[Mm]266\.5[^"]*h18\.5z" fill="#4B2422"\/>/g, // 왼쪽
  /<path d="[Mm]500\.\d+[^"]*h-18\.5z" fill="#4B2422"\/>/g, // 오른쪽
];

/** 속눈썹만 제거한다. 눈 모양(크게 뜬/웃는/작은)과 무관하게 동작한다. */
export function removeLashes(svg) {
  let out = svg;
  for (const re of LASH_PATHS) {
    re.lastIndex = 0;
    if (!re.test(out)) warnMissing("속눈썹");
    out = out.replace(re, "");
  }
  return out;
}

// ── 눈 크기 ──────────────────────────────────────────────────────────────
// 빌트인 눈은 '크게 뜬'과 '웃는' 둘 다 큼직해서, 눈이 작은 사람을 표현할 방법이 없었다.
// (그래서 사진 분석이 자꾸 '감은 눈'을 골랐다 — 지금은 감은 눈을 목록에서 뺐다.)
//
// 새 눈을 그리는 대신 '크게 뜬' 눈을 각자의 중심을 기준으로 줄인다. 그림은 원본
// 그대로라 화풍이 안 깨지고, 좌우를 따로 감싸야 눈 간격이 유지된다
// (한 축으로 줄이면 두 눈이 가운데로 몰린다).
// 빌트인 눈 변형별 좌/우 시작 좌표와 눈동자 중심. 축소 기준점으로 쓴다.
const EYE_ANCHORS_XY = {
  wide: { l: "M321.5 373.47", r: "M445.56 373.47", cl: [314, 413.5], cr: [453, 413.5] },
  happy: { l: "M318.5 380.68", r: "M448.65 380.68", cl: [314, 407.7], cr: [453, 407.7] },
};

/**
 * 지정한 빌트인 눈(base)을 factor 배로 줄인다(1 이면 그대로).
 * inset 은 두 눈을 안쪽으로 당기는 픽셀 수 — 눈이 작아지면 간격이 넓어 보여서 조금 좁힌다.
 * 좌우를 각자의 중심 기준으로 감싸기 때문에 축소만으로는 간격이 그대로다.
 */
export function scaleEyes(svg, factor, base = "wide", inset = 0) {
  if ((!factor || factor === 1) && !inset) return svg;
  const a = EYE_ANCHORS_XY[base];
  if (!a) return svg;
  const li = svg.indexOf(a.l);
  const ri = svg.indexOf(a.r);
  if (li < 0 || ri < 0) return warnMissing("눈 크기"), svg;

  const lStart = svg.lastIndexOf("<path", li);
  const rStart = svg.lastIndexOf("<path", ri);
  // 눈 구간의 끝 = 눈썹 그룹이 시작되는 곳
  const browsAt = svg.search(NEUTRAL_BROWS_RE);
  if (lStart < 0 || rStart <= lStart || browsAt <= rStart) return warnMissing("눈 크기"), svg;

  const f = factor || 1;
  const wrap = (chunk, [cx, cy], dx) =>
    `<g transform="translate(${cx + dx} ${cy}) scale(${f}) translate(${-cx} ${-cy})">${chunk}</g>`;

  return (
    svg.slice(0, lStart) +
    wrap(svg.slice(lStart, rStart), a.cl, inset) + // 왼눈은 오른쪽으로
    wrap(svg.slice(rStart, browsAt), a.cr, -inset) + // 오른눈은 왼쪽으로
    svg.slice(browsAt)
  );
}

// ── 눈썹 (모양 + 두께) ────────────────────────────────────────────────────
// 빌트인 눈썹은 '채워진 path' 라서 두께만 따로 조절할 수가 없다.
// 그래서 선(stroke)으로 다시 그린다. stroke-width 가 곧 눈썹 두께가 된다.
// 눈처럼 교체 방식이라, 커스텀 눈썹을 쓸 땐 항상 'neutral' 로 생성한 뒤 그 자리를 바꾼다.
// 고정 문자열로 잡으면 안 된다. 소스에는 fill="undefined" 로 적혀 있지만
// DiceBear 가 출력할 때 그 자리에 '선택된 머리색'을 넣어버린다(예: fill="#2c1b18").
