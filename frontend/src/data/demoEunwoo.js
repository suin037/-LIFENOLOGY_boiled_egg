function addDays(dateKey, k) {
  const t = new Date(dateKey + "T00:00:00");
  t.setDate(t.getDate() + k);
  const p = (x) => String(x).padStart(2, "0");
  return `${t.getFullYear()}-${p(t.getMonth() + 1)}-${p(t.getDate())}`;
}

